/**
 * Copies the deployment addresses and the ABIs the interface actually needs into
 * web/generated. Keeping this a generated artifact means the front end can never drift
 * from the contracts it is talking to: change a contract, recompile, re-export.
 *
 *   node scripts/export-frontend.js
 */
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const outDir = path.join(root, "web", "generated");
const CONTRACTS = ["QuantSwapFactory", "QuantSwapRouter", "QuantSwapPair", "QuantSwapOracle", "MockERC20", "WETH9"];

function artifactAbi(name) {
  const matches = walk(path.join(root, "artifacts", "contracts")).filter(
    (file) => path.basename(file) === `${name}.json` && !file.endsWith(".dbg.json")
  );
  if (matches.length === 0) throw new Error(`No artifact for ${name}. Run: npx hardhat compile`);
  return JSON.parse(fs.readFileSync(matches[0], "utf8")).abi;
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

function main() {
  fs.mkdirSync(outDir, { recursive: true });

  const deploymentsDir = path.join(root, "deployments");
  const deployments = {};
  if (fs.existsSync(deploymentsDir)) {
    for (const file of fs.readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
      const deployment = JSON.parse(fs.readFileSync(path.join(deploymentsDir, file), "utf8"));
      deployments[deployment.chainId] = deployment;
    }
  }
  fs.writeFileSync(path.join(outDir, "deployments.json"), `${JSON.stringify(deployments, null, 2)}\n`);

  const lines = [
    "// Generated by scripts/export-frontend.js. Do not edit by hand.",
    "",
  ];
  for (const name of CONTRACTS) {
    lines.push(`export const ${lowerFirst(name)}Abi = ${JSON.stringify(artifactAbi(name))} as const;`);
    lines.push("");
  }
  fs.writeFileSync(path.join(outDir, "abis.ts"), lines.join("\n"));

  console.log(`exported ${Object.keys(deployments).length} deployment(s) and ${CONTRACTS.length} ABIs to web/generated`);
}

function lowerFirst(value) {
  return value.charAt(0).toLowerCase() + value.slice(1);
}

main();
